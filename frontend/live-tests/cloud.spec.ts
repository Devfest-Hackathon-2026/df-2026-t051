import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';

test('real private service renders a real Gemini extraction', async ({page,request}) => {
  test.setTimeout(120000);
  const health = await request.get('/api/health');
  expect(health.ok()).toBeTruthy();
  const config = await (await request.get('/api/config')).json();
  test.skip(config.authMode!=='google_iam','This earlier validation flow uses IAM teacher authentication. Use firebase.spec.ts for Firebase.');
  expect(config.demo).toBe(false);
  expect(config.authMode).toBe('google_iam');
  await page.goto('/');
  await expect(page.getByRole('heading',{level:1})).toBeVisible();
  await page.locator('#chart-file').setInputFiles('../backend/tests/fixtures/sample.png');
  const pending = page.waitForResponse(r => r.url().endsWith('/api/analyze'));
  await page.getByRole('button',{name:'グラフを読み取る'}).click();
  const response = await pending;
  expect(response.status()).toBe(200);
  const result = await response.json();
  expect(result.source).toBe('gemini');
  expect(result.status).toBe('unreviewed');
  expect(result.extraction.categories.map((c:{value:number})=>c.value)).toEqual([12,18]);
  await expect(page.getByRole('cell',{name:'12',exact:true}).first()).toBeVisible();
  await expect(page.getByRole('heading',{name:'読み取り結果'})).toBeFocused();
  const violations = (await new AxeBuilder({page}).analyze()).violations;
  expect(violations).toEqual([]);
  const jpeg = await request.post('/api/analyze',{multipart:{file:{name:'sample.jpg',mimeType:'image/jpeg',buffer:fs.readFileSync('../backend/tests/fixtures/sample.jpg')}}});
  expect(jpeg.status()).toBe(200);
  const jpegResult = await jpeg.json();
  expect(jpegResult.source).toBe('gemini');
  expect(jpegResult.extraction.categories.map((c:{value:number})=>c.value)).toEqual([12,18]);
  await page.locator('#chart-file').setInputFiles('../backend/tests/fixtures/uncertain.png');
  const uncertainPending = page.waitForResponse(r=>r.url().endsWith('/api/analyze'));
  await page.getByRole('button',{name:'グラフを読み取る'}).click();
  const uncertain = await uncertainPending;
  expect(uncertain.status()).toBe(200);
  const uncertainResult = await uncertain.json();
  expect(uncertainResult.extraction.categories[1].value).toBeNull();
  await expect(page.getByRole('table',{name:'AI抽出データ（教員確認前）'}).getByRole('cell',{name:'未確定',exact:true})).toBeVisible();
  let persistence:unknown=null;
  if(config.persistence) {
    await page.getByRole('spinbutton',{name:'項目1の数値'}).fill('14');
    const saving=page.waitForResponse(r=>r.url().endsWith('/api/drafts')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'未承認として保存'}).click();
    const savedResponse=await saving;
    expect(savedResponse.status()).toBe(201);
    const saved=await savedResponse.json();
    const draftPath=`/api/drafts/${saved.id}`;
    expect((await request.get(draftPath+'/approved')).status()).toBe(404);
    expect((await request.get('/api/materials/'+saved.id)).status()).toBe(404);
    const confirm=page.getByRole('checkbox',{name:'元画像と全項目を照合し、未確定の数値・単位を確認しました。'});
    await expect(page.getByRole('button',{name:'確認して承認版を作成'})).toBeDisabled();
    await page.getByRole('spinbutton',{name:'項目1の数値'}).fill('13');
    await expect(confirm).toBeDisabled();
    const updating=page.waitForResponse(r=>r.url().endsWith(draftPath)&&r.request().method()==='PUT');
    await page.getByRole('button',{name:'修正を保存'}).click();
    expect((await updating).status()).toBe(200);
    const current=await (await request.get(draftPath)).json();
    const stale=await request.put(draftPath,{data:{expected_version:1,data:current.data}});
    expect(stale.status()).toBe(409);
    const unconfirmed=await request.post(draftPath+'/approve',{data:{expected_version:2,confirmed:false}});
    expect(unconfirmed.status()).toBe(422);
    await confirm.check();
    const approval=page.waitForResponse(r=>r.url().endsWith(draftPath+'/approve'));
    await page.getByRole('button',{name:'確認して承認版を作成'}).click();
    const approvalResponse=await approval;
    expect(approvalResponse.status()).toBe(200);
    const frozen=await approvalResponse.json();
    await expect(page.getByRole('heading',{name:'承認版を作成しました'})).toBeFocused();
    await expect(page.getByRole('spinbutton',{name:'項目1の数値'})).toBeDisabled();
    expect(frozen.data.categories.map((c:{value:number|null})=>c.value)).toEqual([13,null]);
    const forbidden=await request.put(draftPath,{data:{expected_version:3,data:{...current.data,title:'Should never overwrite'}}});
    expect(forbidden.status()).toBe(409);
    const reread=await (await request.get(draftPath+'/approved')).json();
    expect(reread).toEqual(frozen);
    expect((await request.post(draftPath+'/approve',{data:{expected_version:3,confirmed:true}})).status()).toBe(409);
    expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
    persistence={draftId:saved.id,approvedSnapshot:frozen,unapprovedReadStatus:404,staleUpdateStatus:stale.status(),unconfirmedStatus:unconfirmed.status(),updateAfterApprovalStatus:forbidden.status(),snapshotUnchanged:true};
  }
  fs.mkdirSync('../docs/verification',{recursive:true});
  fs.writeFileSync('../docs/verification/cloud-live.json',JSON.stringify({timestamp:new Date().toISOString(),target:process.env.CHARTBRIDGE_LIVE_URL ?? 'http://127.0.0.1:8085',health:health.status(),demo:false,authMode:config.authMode,apiStatus:response.status(),result,jpegResult,uncertainResult,axeViolations:violations.length,persistence},null,2));
  await page.screenshot({path:'../docs/verification/cloud-live.png',fullPage:true});
});
